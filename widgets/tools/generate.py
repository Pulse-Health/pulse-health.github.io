#!/usr/bin/env python3
"""Generates the Swift and Kotlin widget-snapshot types from schema.py, and embeds fixtures/preview.json.

Run from anywhere:  python3 widgets/tools/generate.py        (writes the files listed in schema.py)
                    python3 widgets/tools/generate.py --check  (fails when a generated file is out of date)
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
import schema  # noqa: E402

SWIFT_OUT = os.path.join(ROOT, "ios/Packages/PulseStrengthKit/Sources/PulseStrengthCore/Widgets/WidgetSnapshot.generated.swift")
SWIFT_PREVIEW_OUT = os.path.join(ROOT, "ios/Packages/PulseStrengthKit/Sources/PulseStrengthCore/Widgets/WidgetSnapshotPreview.generated.swift")
KOTLIN_OUT = os.path.join(ROOT, "android/core/src/main/kotlin/health/pulse/strength/core/widgets/WidgetSnapshot.generated.kt")
KOTLIN_PREVIEW_OUT = os.path.join(ROOT, "android/core/src/main/kotlin/health/pulse/strength/core/widgets/WidgetSnapshotPreview.generated.kt")
PREVIEW_JSON = os.path.join(ROOT, "widgets/fixtures/preview.json")

SCALARS = {"String", "Int", "Double", "Bool", "Date", "UUID"}
ENUM_NAMES = {name for name, _, _ in schema.ENUMS}
STRUCT_NAMES = {name for name, _, _ in schema.STRUCTS}
HEADER = "GENERATED by widgets/tools/generate.py from widgets/tools/schema.py. Do not edit; change the schema and regenerate."


def parse_type(text):
    """-> (kind, base, optional) with kind in scalar|enum|struct|external|list ; for lists base is the element type text."""
    optional = text.endswith("?")
    if optional:
        text = text[:-1]
    if text.startswith("[") and text.endswith("]"):
        return ("list", text[1:-1], optional)
    if text in SCALARS:
        return ("scalar", text, optional)
    if text in ENUM_NAMES:
        return ("enum", text, optional)
    if text in STRUCT_NAMES:
        return ("struct", text, optional)
    if text in schema.EXTERNAL:
        return ("external", text, optional)
    raise SystemExit("unknown type in schema: " + text)


# ---------------------------------------------------------------------------------------------------------------- Swift
def swift_type(text):
    kind, base, optional = parse_type(text)
    if kind == "list":
        inner = swift_type(base)
        t = "[" + inner + "]"
    else:
        t = base
    return t + ("?" if optional else "")


def swift_doc(lines, indent):
    out = []
    for line in lines:
        if line:
            out.append(indent + "/// " + line)
    return out


def gen_swift():
    out = ["// " + HEADER, "", "import Foundation", ""]
    for name, doc, cases in schema.ENUMS:
        out += swift_doc([doc], "")
        out.append("public enum %s: String, Codable, Hashable, Sendable, CaseIterable {" % name)
        for c in cases:
            out.append("    case %s" % c)
        out += ["}", ""]
    for name, doc, fields in schema.STRUCTS:
        out += swift_doc([doc], "")
        out.append("public struct %s: Codable, Hashable, Sendable {" % name)
        if name == "WidgetSnapshot":
            out.append("    /// Bump when a field changes meaning; readers ignore snapshots with a higher version.")
            out.append("    public static let currentSchemaVersion = 1")
            out.append("")
        for fname, ftype, default, fdoc in fields:
            out += swift_doc([fdoc], "    ")
            out.append("    public var %s: %s" % (fname, swift_type(ftype)))
        out.append("")
        params = []
        for fname, ftype, default, fdoc in fields:
            p = "%s: %s" % (fname, swift_type(ftype))
            if default is not None:
                p += " = " + default
            elif ftype.endswith("?"):
                p += " = nil"
            params.append(p)
        if len(params) <= 3:
            out.append("    public init(%s) {" % ", ".join(params))
        else:
            out.append("    public init(")
            out.append(",\n".join("        " + p for p in params))
            out.append("    ) {")
        for fname, _, _, _ in fields:
            out.append("        self.%s = %s" % (fname, fname))
        out += ["    }", "}", ""]
    return "\n".join(out)


def gen_swift_preview(raw_json):
    return "\n".join([
        "// " + HEADER,
        "",
        "import Foundation",
        "",
        "public extension WidgetSnapshot {",
        "    /// A complete, hand-made snapshot (widgets/fixtures/preview.json): the data behind widget previews, placeholders",
        "    /// and the snapshot tests. It is idealised on purpose (3 of 4 workouts this week, a fresh personal record) so that",
        "    /// every widget has something to show; the real builder's output for the demo data is checked separately.",
        "    static var preview: WidgetSnapshot {",
        "        // The JSON is part of this file, so a decoding failure is a programming error caught by the tests.",
        "        guard let data = previewJSON.data(using: .utf8),",
        "              let snapshot = try? StrengthJSON.makeDecoder().decode(WidgetSnapshot.self, from: data)",
        "        else { fatalError(\"widgets/fixtures/preview.json does not match the WidgetSnapshot schema\") }",
        "        return snapshot",
        "    }",
        "",
        "    /// The raw JSON of `preview`.",
        '    static let previewJSON = #"""',
        raw_json.rstrip("\n"),
        '"""#',
        "}",
        "",
    ])


# --------------------------------------------------------------------------------------------------------------- Kotlin
def kotlin_type(text):
    kind, base, optional = parse_type(text)
    if kind == "list":
        t = "List<%s>" % kotlin_type(base)
    elif kind == "scalar":
        t = {"String": "String", "Int": "Int", "Double": "Double", "Bool": "Boolean", "Date": "Instant", "UUID": "String"}[base]
    else:
        t = base
    return t + ("?" if optional else "")


def kotlin_default(ftype, default):
    if default is None:
        return "null" if ftype.endswith("?") else None
    if default == "nil":
        return "null"
    if default == "[]":
        return "emptyList()"
    kind, base, _ = parse_type(ftype)
    if kind == "scalar" and base == "Double" and re.fullmatch(r"-?\d+", default):
        return default + ".0"
    return default


def kotlin_enum_entry(case):
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", case).upper()


def gen_kotlin():
    out = [
        "// " + HEADER,
        "@file:UseSerializers(InstantSerializer::class)",
        "",
        "package health.pulse.strength.core.widgets",
        "",
        "import health.pulse.strength.core.InstantSerializer",
        "import health.pulse.strength.core.MuscleGroup",
        "import health.pulse.strength.core.WorkoutSnapshot",
        "import java.time.Instant",
        "import kotlinx.serialization.SerialName",
        "import kotlinx.serialization.Serializable",
        "import kotlinx.serialization.UseSerializers",
        "",
    ]
    for name, doc, cases in schema.ENUMS:
        out.append("/** %s */" % doc)
        out.append("@Serializable")
        out.append("enum class %s {" % name)
        for c in cases:
            out.append('    @SerialName("%s") %s,' % (c, kotlin_enum_entry(c)))
        out += ["}", ""]
    for name, doc, fields in schema.STRUCTS:
        out.append("/** %s */" % doc)
        out.append("@Serializable")
        out.append("data class %s(" % name)
        for fname, ftype, default, fdoc in fields:
            d = kotlin_default(ftype, default)
            line = "    val %s: %s" % (fname, kotlin_type(ftype))
            if d is not None:
                line += " = " + d
            out.append(line + ",")
        if name == "WidgetSnapshot":
            out.append(") {")
            out.append("    companion object {")
            out.append("        /** Bump when a field changes meaning; readers ignore snapshots with a higher version. */")
            out.append("        const val CURRENT_SCHEMA_VERSION = 1")
            out.append("    }")
            out.append("}")
        else:
            out.append(")")
        out.append("")
    return "\n".join(out)


def gen_kotlin_preview(raw_json):
    escaped = raw_json.rstrip("\n").replace("$", "${'$'}")
    return "\n".join([
        "// " + HEADER,
        "package health.pulse.strength.core.widgets",
        "",
        "/**",
        " * A complete, hand-made snapshot (widgets/fixtures/preview.json): the data behind widget previews and placeholders. It is",
        " * idealised on purpose (3 of 4 workouts this week, a fresh personal record) so that every widget has something to show.",
        " */",
        "val WidgetSnapshot.Companion.preview: WidgetSnapshot",
        "    get() = WidgetJson.decodeSnapshot(WIDGET_SNAPSHOT_PREVIEW_JSON)",
        "",
        "/** The raw JSON of [preview]. */",
        'const val WIDGET_SNAPSHOT_PREVIEW_JSON: String = """',
        escaped,
        '"""',
        "",
    ])


# ---------------------------------------------------------------------------------------------------------- validation
def validate(value, ftype, path):
    kind, base, optional = parse_type(ftype)
    if value is None:
        if not optional:
            raise SystemExit("preview.json: %s is null but %s is not optional" % (path, ftype))
        return
    if kind == "list":
        if not isinstance(value, list):
            raise SystemExit("preview.json: %s must be a list" % path)
        for i, item in enumerate(value):
            validate(item, base, "%s[%d]" % (path, i))
    elif kind == "scalar":
        ok = {
            "String": isinstance(value, str), "UUID": isinstance(value, str),
            "Date": isinstance(value, str) and re.fullmatch(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(\.\d+)?Z", value) is not None,
            "Int": isinstance(value, int) and not isinstance(value, bool),
            "Double": isinstance(value, (int, float)) and not isinstance(value, bool),
            "Bool": isinstance(value, bool),
        }[base]
        if not ok:
            raise SystemExit("preview.json: %s is not a valid %s: %r" % (path, base, value))
    elif kind == "enum":
        cases = next(c for n, _, c in schema.ENUMS if n == base)
        if value not in cases:
            raise SystemExit("preview.json: %s must be one of %s" % (path, cases))
    elif kind == "struct":
        fields = next(f for n, _, f in schema.STRUCTS if n == base)
        if not isinstance(value, dict):
            raise SystemExit("preview.json: %s must be an object" % path)
        names = {f[0] for f in fields}
        for key in value:
            if key not in names:
                raise SystemExit("preview.json: unknown key %s.%s" % (path, key))
        for fname, ft, default, _ in fields:
            if fname not in value:
                if default is None and not ft.endswith("?"):
                    raise SystemExit("preview.json: missing required %s.%s" % (path, fname))
                continue
            validate(value[fname], ft, path + "." + fname)
    elif kind == "external":
        if base == "MuscleGroup" and value not in ("Chest", "Back", "Shoulders", "Arms", "Legs", "Core"):
            raise SystemExit("preview.json: %s is not a MuscleGroup" % path)
        # WorkoutSnapshot is validated by the platform tests that decode it.


def main():
    check = "--check" in sys.argv
    with open(PREVIEW_JSON, "r", encoding="utf-8") as handle:
        raw = handle.read()
    validate(json.loads(raw), "WidgetSnapshot", "$")
    pretty = json.dumps(json.loads(raw), indent=2, ensure_ascii=False)
    outputs = {
        SWIFT_OUT: gen_swift(),
        SWIFT_PREVIEW_OUT: gen_swift_preview(pretty),
        KOTLIN_OUT: gen_kotlin(),
        KOTLIN_PREVIEW_OUT: gen_kotlin_preview(pretty),
    }
    stale = []
    for path, text in outputs.items():
        current = None
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as handle:
                current = handle.read()
        if current != text:
            stale.append(path)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8") as handle:
                    handle.write(text)
                print("wrote", os.path.relpath(path, ROOT))
    if check and stale:
        print("out of date:\n  " + "\n  ".join(os.path.relpath(p, ROOT) for p in stale))
        sys.exit(1)
    if not stale:
        print("up to date")


if __name__ == "__main__":
    main()
